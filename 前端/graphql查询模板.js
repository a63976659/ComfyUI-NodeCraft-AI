/**
 * 聊天流式订阅（WebSocket / graphql-ws）
 * 用途：主聊天通道，逐 token 推送 AI 响应
 * 回调：onData 接收 { 内容, 完成 }；完成=true 表示生成结束
 */
export const CHAT_STREAM = `
subscription 聊天流(
    $会话ID: String!,
    $消息内容: String!,
    $插件上下文: String!,
    $模型来源: String!
) {
    聊天流(
        会话ID: $会话ID,
        消息内容: $消息内容,
        插件上下文: $插件上下文,
        模型来源: $模型来源
    ) {
        内容
        完成
    }
}
`;

