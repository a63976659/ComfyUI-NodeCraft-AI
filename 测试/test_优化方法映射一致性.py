"""优化方法映射表与知识库目录的一致性断言测试。

背景：优化面板欢迎页的快捷入口按钮由四处声明共同决定，靠人工同步且此前无测试保护——
  1. `知识库/优化插件/**/*.md`            实际文档（后端 rglob 扫描）
  2. `后端/插件浏览路由.py`               `_优化方法隐藏文档` / `_优化方法展示名`
  3. `前端/优化面板.js`                   `_优化分类图标` / `_优化方法文案键`
  4. `前端/i18n.js`                       `optimize.method_*` 中英文案
任一处改名、新增或删除而未同步其余几处时，界面会静默降级：
按钮显示冗长的文档全名、总览类文档变成按钮、分类图标回退为默认「◆」，或英文界面下按钮仍显示中文。

本测试用纯静态正则解析源码，不导入任何模块，因此无需 ComfyUI 运行时（`server` 模块）即可执行：
    pytest 测试/                     # 有 pytest 时
    python 测试/test_优化方法映射一致性.py   # 无 pytest 时直接运行
"""
import re
from pathlib import Path

项目根 = Path(__file__).resolve().parent.parent
知识库优化插件目录 = 项目根 / "知识库" / "优化插件"
插件浏览路由源码 = (项目根 / "后端" / "插件浏览路由.py").read_text(encoding="utf-8")
优化面板源码 = (项目根 / "前端" / "优化面板.js").read_text(encoding="utf-8")
i18n源码 = (项目根 / "前端" / "i18n.js").read_text(encoding="utf-8")


def _提取字面量块(源码: str, 变量名: str) -> str:
    """截取 `变量名 = { ... }` 的花括号内文本（这些常量均为单层，无嵌套花括号）"""
    起 = 源码.find(f"{变量名} = {{")
    assert 起 != -1, f"未在源码中找到常量 {变量名}，可能已被改名或删除"
    左 = 源码.index("{", 起)
    右 = 源码.index("}", 左)
    return 源码[左 + 1:右]


def _解析集合元素(源码: str, 变量名: str) -> set[str]:
    """解析 set 字面量的全部字符串元素"""
    return set(re.findall(r"""["']([^"']+)["']""", _提取字面量块(源码, 变量名)))


def _解析字典键(源码: str, 变量名: str) -> set[str]:
    """解析 dict / JS 对象字面量的全部键名（只取冒号左侧的字符串）"""
    return set(re.findall(r"""["']([^"']+)["']\s*:""", _提取字面量块(源码, 变量名)))


def _解析字典值(源码: str, 变量名: str) -> set[str]:
    """解析 dict / JS 对象字面量的全部值（只取冒号右侧的字符串）"""
    return set(re.findall(r""":\s*["']([^"']+)["']""", _提取字面量块(源码, 变量名)))


def _实际文档名集合() -> set[str]:
    """知识库/优化插件 下全部 .md 的文件名（不含扩展名），与后端 rglob 口径一致"""
    return {f.stem for f in 知识库优化插件目录.rglob("*.md") if not f.name.startswith(".")}


def _实际分类目录集合() -> set[str]:
    """含 .md 的子目录名，即后端返回的 category 取值域（根目录文档 category 为空，不计入）"""
    return {
        f.parent.name
        for f in 知识库优化插件目录.rglob("*.md")
        if not f.name.startswith(".") and f.parent != 知识库优化插件目录
    }


def test_隐藏文档均真实存在():
    """`_优化方法隐藏文档` 不应残留已删除或已改名的文档（死条目会让隐藏意图失效）"""
    隐藏 = _解析集合元素(插件浏览路由源码, "_优化方法隐藏文档")
    死条目 = 隐藏 - _实际文档名集合()
    assert not 死条目, f"_优化方法隐藏文档 中存在实际不存在的文档: {sorted(死条目)}"


def test_展示名均真实存在():
    """`_优化方法展示名` 不应残留死条目（改名后旧键永远命中不到，等于没配）"""
    展示名 = _解析字典键(插件浏览路由源码, "_优化方法展示名")
    死条目 = 展示名 - _实际文档名集合()
    assert not 死条目, f"_优化方法展示名 中存在实际不存在的文档: {sorted(死条目)}"


def test_每个可见文档都配了展示名():
    """未被隐藏的文档必须有简洁展示名，否则按钮会显示冗长的文档全名"""
    隐藏 = _解析集合元素(插件浏览路由源码, "_优化方法隐藏文档")
    展示名 = _解析字典键(插件浏览路由源码, "_优化方法展示名")
    缺配置 = _实际文档名集合() - 隐藏 - 展示名
    assert not 缺配置, (
        f"以下文档会作为按钮显示但未配展示名: {sorted(缺配置)}；"
        f"请在 _优化方法展示名 中补充简洁名，或加入 _优化方法隐藏文档"
    )


def test_展示名与隐藏文档不重叠():
    """同一文档既隐藏又配展示名属于配置矛盾，展示名永远不会生效"""
    隐藏 = _解析集合元素(插件浏览路由源码, "_优化方法隐藏文档")
    展示名 = _解析字典键(插件浏览路由源码, "_优化方法展示名")
    重叠 = 隐藏 & 展示名
    assert not 重叠, f"以下文档同时出现在隐藏列表与展示名映射中: {sorted(重叠)}"


def test_每个分类目录都配了前端图标():
    """`前端/优化面板.js` 的 `_优化分类图标` 需覆盖全部分类目录，否则图标回退为默认「◆」"""
    图标分类 = _解析字典键(优化面板源码, "_优化分类图标")
    缺图标 = _实际分类目录集合() - 图标分类
    assert not 缺图标, (
        f"以下分类目录在前端 _优化分类图标 中缺少图标: {sorted(缺图标)}"
    )


def test_前端图标无多余分类():
    """前端图标表不应残留已删除的分类目录"""
    图标分类 = _解析字典键(优化面板源码, "_优化分类图标")
    多余 = 图标分类 - _实际分类目录集合()
    assert not 多余, f"前端 _优化分类图标 中存在实际不存在的分类目录: {sorted(多余)}"


def test_双语文案键与展示名键集一致():
    """`_优化方法文案键` 需与后端 `_优化方法展示名` 覆盖同一批文档，

    缺键会让该按钮回退到后端中文 display（英文界面下显示中文），
    多余的键则是改名后残留的死条目。
    """
    展示名 = _解析字典键(插件浏览路由源码, "_优化方法展示名")
    文案键 = _解析字典键(优化面板源码, "_优化方法文案键")
    assert 文案键 == 展示名, (
        f"前端 _优化方法文案键 缺少: {sorted(展示名 - 文案键)}；"
        f"多余: {sorted(文案键 - 展示名)}"
    )


def test_双语文案键在i18n中双语齐备():
    """每个 `optimize.method_*` 键必须在 i18n.js 的中、英两个字典中各定义一次"""
    缺失 = {}
    for 键 in sorted(_解析字典值(优化面板源码, "_优化方法文案键")):
        次数 = len(re.findall(rf"""["']{re.escape(键)}["']\s*:""", i18n源码))
        if 次数 != 2:
            缺失[键] = 次数
    assert not 缺失, f"以下 i18n 键在 i18n.js 中的定义次数不为 2（应中英各一次）: {缺失}"


