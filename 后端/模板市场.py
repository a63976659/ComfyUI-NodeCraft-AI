def _构建功能对照表(template_id: str, entry_type: str, options: list, language: str = "zh-CN") -> str:
    """生成 README 末尾的功能对照表，帮助对话智能体把用户口语术语映射到代码位置"""
    _is_en = language == "en"
    rows = []
    if template_id == "ui_extension":
        row = (ENTRY_TYPE_README_ROWS_EN if _is_en else ENTRY_TYPE_README_ROWS).get(entry_type)
        if row:
            rows.append(row)
        for opt in options:
            row = (OPTION_README_ROWS_EN if _is_en else OPTION_README_ROWS).get(opt)
            if row:
                rows.append(row)
    else:
        row = (TEMPLATE_README_ROWS_EN if _is_en else TEMPLATE_README_ROWS).get(template_id)
        if row:
            rows.append(row)

    if not rows:
        return ""

    if _is_en:
        return (
            "\n## Feature Map (AI Guide)\n\n"
            "> This project was created from a NodeCraft AI template. The table below maps common\n"
            "> user terms to files and code locations. Locate via this table first, then confirm\n"
            "> scope with the [Template/Entry/Option] comment markers in the code.\n\n"
            "| What the user may say | File and code location |\n"
            "| --- | --- |\n"
            + "\n".join(rows) + "\n"
        )
    return (
        "\n## 功能对照表（AI 修改指引）\n\n"
        "> 本项目由 NodeCraft AI 模板创建。下表将用户常用叫法映射到对应文件与代码位置，\n"
        "> AI 助手修改功能时请先按此表定位，再结合代码内【模板类型/入口类型/勾选项】注释标记确认范围。\n\n"
        "| 用户可能的叫法 | 对应文件与代码位置 |\n"
        "| --- | --- |\n"
        + "\n".join(rows) + "\n"
    )

