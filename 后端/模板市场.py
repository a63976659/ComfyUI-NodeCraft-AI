class TemplateMarket:
    """模板市场管理器"""

    def __init__(self, custom_nodes_dir: Path):
        self.custom_nodes_dir = custom_nodes_dir

    def list_templates(self) -> List[Dict]:
        """获取所有可用模板"""
        return [
            {"id": t["id"], "name": t["name"], "description": t["description"], "category": t["category"]}
            for t in BUILTIN_TEMPLATES
        ]

    def get_template(self, template_id: str) -> Dict:
        """获取模板详情"""
        for t in BUILTIN_TEMPLATES:
            if t["id"] == template_id:
                return t
        return None

    def create_from_template(self, template_id: str, project_name: str,
                             entry_type: str = "canvas", options: list = None,
                             custom_names: dict = None, language: str = "zh-CN") -> Dict:
        """从模板创建新项目

        entry_type: UI 扩展入口类型（canvas/sidebar/topMenu/statusBar），仅对 ui_extension 模板生效
        options: 附加能力列表（如 shortcuts/settings），在生成的 JS 中追加对应代码块
        custom_names: 用户自定义名称，根据 entry_type 包含不同键：
            - canvas: {"category": "节点分类名称"}
            - sidebar: {"sidebar_title": "侧边栏显示名称"}
            - topMenu: {"menu_label": "菜单显示名称"}
            - statusBar: {"status_label": "状态栏显示名称"}
        language: 界面语言（zh-CN/en），决定目录名与生成内容语言：
            - zh-CN: 节点/、网页资源/、后端/ + 中文注释与显示名
            - en: nodes/、web/、backend/ + 英文注释与显示名
        """
        if options is None:
            options = []
        if custom_names is None:
            custom_names = {}

        template = self.get_template(template_id)
        if not template:
            return {"success": False, "message": f"模板 '{template_id}' 不存在"}

        # 验证项目名
        if not re.match(r'^[a-zA-Z0-9_-]+$', project_name):
            return {"success": False, "message": "项目名称只能包含字母、数字、下划线和连字符"}

        if len(project_name) > 128:
            return {"success": False, "message": "项目名称过长（最大128字符）"}

        target_dir = self.custom_nodes_dir / project_name
        if target_dir.exists():
            return {"success": False, "message": f"目录 '{project_name}' 已存在"}

        # 按语言选择模板内容（英文界面优先用英文版，缺失时回退中文版）
        _is_en = language == "en"
        _dirs = _get_language_dirs(language)
        node_dir, web_dir = _dirs["node"], _dirs["web"]
        files = dict(template.get("files_en" if _is_en else "files") or template["files"])

        # 仅 ui_extension 模板根据 entry_type/options 生成差异化 JS
        if template_id == "ui_extension":
            _js_templates = ENTRY_TYPE_JS_TEMPLATES_EN if _is_en else ENTRY_TYPE_JS_TEMPLATES
            js_content = _js_templates.get(entry_type)
            if js_content is not None:
                # sidebar/topMenu/statusBar 使用差异化骨架替换默认 JS
                js_content = js_content.replace("{project_name}", project_name)
                # 替换自定义显示名称占位符（默认值随语言切换）
                if _is_en:
                    js_content = js_content.replace("{sidebar_title}", custom_names.get("sidebar_title", "My Plugin"))
                    js_content = js_content.replace("{menu_label}", custom_names.get("menu_label", "My Command"))
                    js_content = js_content.replace("{status_label}", custom_names.get("status_label", "My Status"))
                else:
                    js_content = js_content.replace("{sidebar_title}", custom_names.get("sidebar_title", "我的插件"))
                    js_content = js_content.replace("{menu_label}", custom_names.get("menu_label", "我的命令"))
                    js_content = js_content.replace("{status_label}", custom_names.get("status_label", "我的状态"))
            else:
                # canvas 或未知类型：使用模板自带的默认 JS（键仍为占位符形式）
                js_content = files.get("{web_dir}/extensions.js", "")

            # 根据 options 在 JS 末尾追加附加代码块
            _snippets = OPTION_JS_SNIPPETS_EN if _is_en else OPTION_JS_SNIPPETS
            for opt in options:
                snippet = _snippets.get(opt)
                if snippet:
                    js_content += snippet.replace("{project_name}", project_name)

            if js_content:
                files["{web_dir}/extensions.js"] = js_content

        # basic_node 模板：替换自定义 CATEGORY（默认分类名随语言切换）
        if template_id == "basic_node":
            _default_category = "🔧 Custom Tools/Basic" if _is_en else "🔧 自定义工具/基础处理"
            custom_category = custom_names.get("category", _default_category)
            for _key in list(files.keys()):
                if _key.endswith(("基础节点.py", "basic_node.py")):
                    files[_key] = files[_key].replace("{custom_category}", custom_category)

        # README 末尾追加功能对照表，让对话智能体读取项目时能理解用户口语术语
        对照表 = _构建功能对照表(template_id, entry_type, options, language)
        if 对照表:
            files["README.md"] = files.get("README.md", "") + 对照表

        # 创建项目目录和文件
        target_dir.mkdir(parents=True)

        # ── 创建标准目录结构（与"自定义插件"保持一致，目录名随语言切换）──
        (target_dir / node_dir).mkdir(exist_ok=True)
        (target_dir / web_dir).mkdir(exist_ok=True)
        # 侧边栏/菜单/状态栏等 UI 扩展类模板额外创建后端目录，放置后端功能文件
        if template_id == "ui_extension":
            (target_dir / _dirs["backend"]).mkdir(exist_ok=True)

        for file_path, content in files.items():
            # 替换目录占位符为实际目录名
            real_path = file_path.replace("{node_dir}", node_dir).replace("{web_dir}", web_dir)
            full_path = target_dir / real_path
            full_path.parent.mkdir(parents=True, exist_ok=True)
            full_path.write_text(content, encoding='utf-8')

        _labels = ENTRY_TYPE_LABELS_EN if _is_en else ENTRY_TYPE_LABELS
        entry_type_label = _labels.get(entry_type, entry_type)
        if _is_en:
            message = f"Project '{project_name}' created (entry type: {entry_type_label})"
        else:
            message = f"项目 '{project_name}' 已创建（入口类型：{entry_type_label}）"
        return {
            "success": True,
            "message": message,
            "path": str(target_dir),
            "entry_type": entry_type,
            "options": options,
        }
